"""Sound for "Cleopatra lived closer to the Moon landing than to the Great Pyramid": open-source sound effects only
(no narration, owner's request), loud.

  python3 scripts/synth_audio.py

Layers from OPEN-SOURCE sources (osfx.py): CC0 OpenGameArt recordings (slams, stones, sci-fi beeps, gong, creatures),
jsfxr, the bundled HyperFrames library, and the numpy kits (sfxlib, foley). Everything used is frozen into assets/sfx/.
Writes assets/audio/mix.wav + captions.js (text cards + the beats the picture shares).
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
import voicelib as V  # noqa: E402

DUR = 22.0
B = dict(GLITCH=1.55, BUILD=1.8, TIMELINE=5.6, BAR1=6.0, BAR2=10.0, ANCIENT=14.0, MAMMOTH=17.6, BACK=20.2)

CARDS = [
    (0.10, 1.55, "CLEOPATRA LIVED CLOSER|TO THE *MOON LANDING*..."),
    (2.00, 5.45, "...THAN TO THE BUILDING|OF THE GREAT *PYRAMID*"),
    (5.80, 9.75, "PYRAMID TO CLEOPATRA:|ABOUT *2,500* YEARS"),
    (9.95, 13.80, "CLEOPATRA TO THE MOON:|ABOUT *2,000* YEARS"),
    (14.20, 17.40, "TO HER, THE PYRAMIDS|WERE ALREADY *ANCIENT*"),
    (17.80, 20.00, "AS THEY WERE BUILT,|*MAMMOTHS* STILL LIVED"),
    (20.40, 21.85, "HISTORY IS *WEIRD*"),
]

os.environ["SFX_DUR"] = str(DUR)
from sfxlib import *  # noqa: E402,F403
import foley as F  # noqa: E402
import osfx  # noqa: E402

osfx.project(ROOT)
amb, fx = Bus(), Bus()

# ---------------------------------------------------------------- 0. hook: slam, braam, a radio beep from the astronaut
fx.put(osfx.sound("oga/100-sfx/slam_01", impact(1.0)), 0.0, 0.9)
fx.put(impact(1.0), 0.0, 0.7)
fx.put(braam(1.5, 55), 0.0, 0.6)
fx.put(osfx.sound("oga/scifi/beep_02", blip(1400)), 0.35, 0.6, 0.6)
fx.put(osfx.sound("oga/scifi/beep_03", blip(1100)), 0.65, 0.5, 0.6)
fx.put(rewind(0.4), B["GLITCH"] - 0.05, 0.7)
fx.put(osfx.lib("glitch-1"), B["GLITCH"], 0.5)

# ---------------------------------------------------------------- 1. the pyramid rises block by block: taiko + stone thuds, desert wind
amb.x += (0.45 * F.wind(DUR, 300, 700, 0.4, seed=2) * (seg(B["BUILD"], B["TIMELINE"], 0.3) + seg(B["ANCIENT"], B["MAMMOTH"], 0.3)))[:, None]
step = (B["TIMELINE"] - B["BUILD"] - 0.6) / 8
for k in range(8):
    tk = B["BUILD"] + 0.2 + (k + 1) * step
    fx.put(taiko(68), tk, 0.8)
    fx.put(osfx.sound(f"oga/100-sfx-2/sfx100v2_stones_0{k % 3 + 1}", thump(120, 0.2, 1.5)), tk, 0.7, (k % 3 - 1) * 0.5)

# ---------------------------------------------------------------- 2. the timeline: whoosh, bars fill with risers, counter ticks, big hits
fx.put(osfx.lib("whoosh-cinematic"), B["TIMELINE"] - 0.25, 0.8)
for b0, col in ((B["BAR1"], 0), (B["BAR2"], 1)):
    fx.put(riser(1.6, 250, 1300), b0, 0.5)
    for k in range(14):
        fx.put(F.tick(2600 + 400 * col, 0.9), b0 + k * 1.6 / 14, 0.45)
    fx.put(osfx.sound("oga/100-sfx/slam_03", impact(0.9)), b0 + 1.6, 0.8)
    fx.put(impact(1.0), b0 + 1.6, 0.6)
    fx.put(osfx.sfxr("pickupCoin", seed=7 + col), b0 + 1.65, 0.45)

# ---------------------------------------------------------------- 3. Cleopatra sees the ancient pyramid: gasp + braam, birds
fx.put(osfx.lib("whoosh"), B["ANCIENT"] - 0.2, 0.7)
fx.put(osfx.sound("oga/creatures/ooh", sweep(0.6, 500, 300)), B["ANCIENT"] + 0.9, 0.7)
fx.put(braam(1.8, 50), B["ANCIENT"] + 0.9, 0.7)
for k in range(3):
    fx.put(F.squawk(47 + k), B["ANCIENT"] + 0.3 + k * 0.7, 0.3, -0.4 + k * 0.3)

# ---------------------------------------------------------------- 4. split screen: snowy wind, heavy mammoth steps, a trumpet roar
fx.put(osfx.lib("whoosh-cinematic"), B["MAMMOTH"] - 0.25, 0.8)
amb.x += (0.5 * F.wind(DUR, 500, 1100, 0.7, seed=8) * seg(B["MAMMOTH"], B["BACK"], 0.3))[:, None]
for k in range(5):
    fx.put(thump(55, 0.35, 2.0), B["MAMMOTH"] + 0.1 + k * 0.33, 0.8, 0.5)
fx.put(osfx.sound("oga/creatures/roar_02", roar(1.4)), B["MAMMOTH"] + 1.0, 0.9, 0.5)
fx.put(osfx.sound("oga/100-sfx-2/sfx100v2_stones_02", thump(120, 0.2, 1.5)), B["MAMMOTH"] + 0.6, 0.5, -0.5)

# ---------------------------------------------------------------- 5. back to the mash-up: a gong, beeps, whoosh into the loop
fx.put(osfx.lib("whoosh-cinematic"), B["BACK"] - 0.25, 0.8)
fx.put(osfx.sound("oga/100-sfx/gong_01", gong(110)), B["BACK"] + 0.2, 0.7)
fx.put(osfx.sound("oga/scifi/beep_02", blip(1400)), B["BACK"] + 0.7, 0.5, 0.6)
fx.put(osfx.lib("whoosh-cinematic"), DUR - 0.6, 0.7)

master(amb, fx, os.path.join(ROOT, "assets", "audio", "mix.wav"), amb_gain=0.6, makeup_db=10.0)

caps = [{"a": a, "b": b, "segs": [V.segs(ln) for ln in text.split("|")]} for a, b, text in CARDS]
with open(os.path.join(ROOT, "captions.js"), "w") as f:
    f.write("// generated by scripts/synth_audio.py: text cards + shared beats (no narration)\n")
    f.write(f"window.DUR = {DUR};\n")
    f.write("window.CAPS = " + json.dumps(caps) + ";\n")
    f.write("window.VO = [];\nwindow.MOUTH = {};\n")
    f.write("window.BEATS = " + json.dumps(B) + ";\n")
print("DUR", DUR)
