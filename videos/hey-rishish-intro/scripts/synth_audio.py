"""Sound for the @hey.rishish intro: open-source sound effects only (no narration, owner's request), kept calm.

  python3 scripts/synth_audio.py

Soft, non-buzzy layers from OPEN-SOURCE sources (osfx.py): CC0 OpenGameArt recordings, the bundled HyperFrames
library, and the numpy kits (sfxlib, foley). Harsh / buzzy sources (saw roars, sfxr power-ups, rockets, cannons,
risers, sizzle) are left out on purpose, and most layers are low-passed so nothing hisses or buzzes.
Everything used is frozen into assets/sfx/. Writes assets/audio/mix.wav + captions.js (timing beats only).
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)

DUR = 6.5
# ---------------------------------------------------------------- the beats (shared with the picture via window.BEATS)
T_TURN = 1.7               # the dragon curls round toward the camera
T_INHALE = 2.6             # its head comes close, rears back, throat glows
T_FIRE = 2.9               # fire bursts in every direction
T_FADE = 3.7               # fire starts fading out
T_TITLE = 3.85             # "WELCOME BACK TO" banner unrolls
T_HANDLE = 4.6             # "@hey." drops in
T_NAME = 5.05              # "rishish" drops in

os.environ["SFX_DUR"] = str(DUR)
from sfxlib import *  # noqa: E402,F403
import foley as F  # noqa: E402
import osfx  # noqa: E402

osfx.project(ROOT)
amb, fx = Bus(), Bus()


def soft(x, hi=3500, lo=60):
    """take the edge off: low-pass (and a gentle high-pass) so nothing buzzes or hisses"""
    return band(x, lo, hi)


# ---------------------------------------------------------------- 0. calm open: a soft gong, wind chimes, a gentle breeze
fx.put(soft(gong(110, 3.0), 2500), 0.0, 0.3)
fx.put(F.sparkle(1.8, seed=9, lo=2500, hi=5000), 0.15, 0.12)                # wind chimes
amb.x += (0.35 * soft(F.wind(DUR, 300, 700, 0.3, seed=4), 1500) * seg(0, T_FIRE, 0.5))[:, None]

# ---------------------------------------------------------------- 1. the dragon swims in from the left: soft air on each curve
fx.put(soft(osfx.lib("whoosh"), 3000), 0.1, 0.35, -0.7)
for k, tw in enumerate([0.55, 1.1, 1.55]):
    fx.put(soft(osfx.sound(f"oga/100-sfx-2/sfx100v2_air_0{k % 3 + 1}", sweep(0.3, 300, 120)), 2500), tw, 0.3, -0.6 + 0.45 * k)

# ---------------------------------------------------------------- 2. curls round to the camera: a slow whoosh + a soft taiko roll
fx.put(soft(osfx.lib("whoosh-cinematic"), 2500), T_TURN - 0.05, 0.4, 0.3)
for tt, sig in drum_roll(T_TURN + 0.2, T_FIRE - 0.05, start_gap=0.3, end_gap=0.1, f=70):
    fx.put(soft(sig, 1200), tt, 0.25)

# ---------------------------------------------------------------- 3. a breath in, then a deep soft "whoomph" of fire
fx.put(soft(osfx.sound("oga/creatures/breath", sweep(0.3, 200, 900)), 3000), T_INHALE - 0.05, 0.4)
fx.put(soft(osfx.lib("whoosh-cinematic"), 2000), T_FIRE - 0.05, 0.55)
fx.put(soft(F.fire(1.6, 53), 1800), T_FIRE, 0.6)
fx.put(soft(thump(45, 1.0, 2.0), 800), T_FIRE, 0.5)
fx.put(soft(reverb(np.concatenate([thump(55, 0.6, 1.5), np.zeros(SR)]), 1.6, 0.4, 21), 1000), T_FIRE, 0.3)
for k in range(3):                                                   # flames drifting past, left and right
    fx.put(soft(osfx.lib("whoosh-short"), 2500), T_FIRE + 0.2 + k * 0.2, 0.18, -0.6 if k % 2 else 0.6)

# ---------------------------------------------------------------- 4. the fire dies down: a soft crackle tail, a few ember ticks
fx.put(soft(F.fire(1.2, 61), 1500) * np.linspace(1, 0, int(1.2 * SR)), T_FADE, 0.3)
for k in range(4):
    fx.put(soft(F.tick(2200, 0.4), 4000), T_FADE + 0.15 + k * 0.17, 0.08, (k % 3 - 1) * 0.5)

# ---------------------------------------------------------------- 5. WELCOME BACK TO @hey.rishish, the dragon slithers back in
fx.put(soft(osfx.sound("oga/100-sfx/paper_02", F.page_flip(97)), 4000), T_TITLE, 0.3)       # banner unrolls
fx.put(soft(osfx.lib("whoosh"), 2500), T_TITLE + 0.15, 0.3, -0.6)                            # dragon glides in
for i in range(12):                       # each letter lands with a soft pop: "@hey." then "rishish"
    fx.put(soft(osfx.lib("pop"), 3500), (T_HANDLE + i * 0.04) if i < 5 else (T_NAME + (i - 5) * 0.04), 0.14, -0.6 + i * 0.1)
fx.put(soft(taiko(75), 1200), T_HANDLE, 0.3)
fx.put(soft(gong(98, 3.0), 2500), T_NAME, 0.22)
chord = [523.25, 659.25, 783.99, 1046.5]
for i, f in enumerate(chord):             # a gentle bell arpeggio into a held chord on the name
    fx.put(bell(f, 1.8), T_NAME - 0.2 + i * 0.06, 0.1)
fx.put(add(*[bell(f, 1.8) for f in chord]), T_NAME + 0.05, 0.07)
fx.put(F.sparkle(1.2, seed=67, lo=2500, hi=5000), T_NAME + 0.1, 0.12)

master(amb, fx, os.path.join(ROOT, "assets", "audio", "mix.wav"), amb_gain=0.6, makeup_db=6.0)
beats = {"TURN": T_TURN, "INHALE": T_INHALE, "FIRE": T_FIRE, "FADE": T_FADE, "TITLE": T_TITLE, "HANDLE": T_HANDLE, "NAME": T_NAME}
with open(os.path.join(ROOT, "captions.js"), "w") as f:
    f.write("// generated by scripts/synth_audio.py: timing beats (no narration in this intro)\n")
    f.write(f"window.DUR = {DUR};\nwindow.CAPS = [];\nwindow.VO = [];\nwindow.MOUTH = {{}};\n")
    f.write("window.BEATS = " + json.dumps(beats) + ";\n")
print("wrote captions.js (beats only)")
